-- FCM credentials belong to a subscriber AND integration. Existing legacy
-- rows without an integration ID remain addressable as a single fixture row.
ALTER TABLE novu_rust_fcm_integrations DROP CONSTRAINT IF EXISTS novu_rust_fcm_integrations_pkey;
ALTER TABLE novu_rust_fcm_integrations ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE novu_rust_fcm_integrations ADD PRIMARY KEY (environment_id, internal_id);
CREATE INDEX IF NOT EXISTS novu_rust_fcm_integrations_lookup_idx
  ON novu_rust_fcm_integrations(environment_id,active,created_at DESC,internal_id DESC);

ALTER TABLE novu_rust_fcm_devices DROP CONSTRAINT IF EXISTS novu_rust_fcm_devices_pkey;
ALTER TABLE novu_rust_fcm_devices ADD COLUMN IF NOT EXISTS channel_order bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS novu_rust_fcm_devices_integration_idx
  ON novu_rust_fcm_devices(environment_id,subscriber_id,integration_internal_id)
  WHERE integration_internal_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS novu_rust_fcm_devices_legacy_idx
  ON novu_rust_fcm_devices(environment_id,subscriber_id)
  WHERE integration_internal_id IS NULL;
CREATE INDEX IF NOT EXISTS novu_rust_fcm_devices_order_idx
  ON novu_rust_fcm_devices(environment_id,subscriber_id,channel_order);
