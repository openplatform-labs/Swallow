//! Experimental v1 topic membership management.
use crate::{ApiError, authenticate, error_at, validation_error};
use axum::{
    Json,
    body::Bytes,
    extract::{OriginalUri, Path, Query, State},
    http::{HeaderMap, StatusCode},
    response::{IntoResponse, Response},
};
use serde_json::{Value, json};
use std::{collections::HashMap, sync::Arc};
use tokio_postgres::Client;

fn subscribers(bytes: &Bytes, path: &str) -> Result<Vec<String>, ApiError> {
    let value: Value = serde_json::from_slice(bytes)
        .map_err(|_| error_at(StatusCode::BAD_REQUEST, "Invalid JSON", "Bad Request", path))?;
    let Some(items) = value.get("subscribers").and_then(Value::as_array) else {
        let mut errors = Vec::new();
        if value.get("subscribers").is_none_or(Value::is_null) {
            errors.push("subscribers should not be null or undefined");
        }
        errors.push("subscribers must be an array");
        let mut response = validation_error(errors);
        response.1.0["path"] = json!(path);
        return Err(response);
    };
    items
        .iter()
        .map(|item| {
            item.as_str().map(str::to_owned).ok_or_else(|| {
                error_at(
                    StatusCode::NOT_IMPLEMENTED,
                    "Subscriber input not implemented",
                    "Not Implemented",
                    path,
                )
            })
        })
        .collect()
}

pub async fn assign(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    Path(topic): Path<String>,
    OriginalUri(uri): OriginalUri,
    bytes: Bytes,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(value) => value,
        Err(error) => return error.into_response(),
    };
    let ids = match subscribers(&bytes, &path) {
        Ok(ids) => ids,
        Err(error) => return error.into_response(),
    };
    let result=db.query_one("WITH topic AS (INSERT INTO novu_rust_topics(environment_id,topic_key,internal_id,name) VALUES ($1,$2,novu_rust_new_objectid(),'Autogenerated-' || $2) ON CONFLICT (environment_id,topic_key) DO UPDATE SET topic_key=EXCLUDED.topic_key RETURNING environment_id,topic_key), found AS MATERIALIZED (SELECT subscriber_id FROM novu_rust_subscribers WHERE environment_id=$1 AND subscriber_id=ANY($3) ORDER BY internal_id), inserted AS (INSERT INTO novu_rust_topic_subscribers(environment_id,topic_key,subscriber_id,identifier) SELECT topic.environment_id,topic.topic_key,found.subscriber_id,'tk_' || topic.topic_key || ':si_' || found.subscriber_id FROM topic CROSS JOIN found ON CONFLICT DO NOTHING RETURNING subscriber_id) SELECT ARRAY(SELECT subscriber_id FROM found),ARRAY(SELECT input.id FROM unnest($3::text[]) WITH ORDINALITY input(id,ord) WHERE NOT EXISTS(SELECT 1 FROM found WHERE subscriber_id=input.id) GROUP BY input.id ORDER BY min(input.ord)),(SELECT count(*) FROM inserted)", &[&env,&topic,&ids]).await;
    match result {
        Ok(row) => {
            let succeeded: Vec<String> = row.get(0);
            let missing: Vec<String> = row.get(1);
            let mut result = json!({"succeeded":succeeded});
            if !missing.is_empty() {
                result["failed"] = json!({"notFound":missing});
            }
            (StatusCode::OK, Json(json!({"data":result}))).into_response()
        }
        Err(_) => error_at(
            StatusCode::INTERNAL_SERVER_ERROR,
            "Internal server error",
            "Internal Server Error",
            &path,
        )
        .into_response(),
    }
}

pub async fn remove(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    Path(topic): Path<String>,
    OriginalUri(uri): OriginalUri,
    bytes: Bytes,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(value) => value,
        Err(error) => return error.into_response(),
    };
    let ids = match subscribers(&bytes, &path) {
        Ok(ids) => ids,
        Err(error) => return error.into_response(),
    };
    match db.execute("DELETE FROM novu_rust_topic_subscribers WHERE environment_id=$1 AND topic_key=$2 AND subscriber_id=ANY($3)", &[&env,&topic,&ids]).await {
        Ok(_)=>StatusCode::NO_CONTENT.into_response(),
        Err(_)=>error_at(StatusCode::INTERNAL_SERVER_ERROR,"Internal server error","Internal Server Error",&path).into_response(),
    }
}

fn topic_error(status: StatusCode, message: &str, path: &str) -> Response {
    let label = match status {
        StatusCode::NOT_FOUND => "Not Found",
        StatusCode::BAD_REQUEST => "Bad Request",
        StatusCode::CONFLICT => "Conflict",
        _ => "Internal Server Error",
    };
    error_at(status, message, label, path).into_response()
}
fn invalid_fields(body: &Value, fields: &[&str], path: &str) -> Option<Response> {
    let mut errors = Vec::new();
    for &field in fields {
        if body.get(field).is_none_or(Value::is_null) {
            errors.push(format!("{field} should not be null or undefined"));
        }
        if !body.get(field).is_some_and(Value::is_string) {
            errors.push(format!("{field} must be a string"));
        }
    }
    if errors.is_empty() {
        return None;
    }
    let messages: Vec<&str> = errors.iter().map(String::as_str).collect();
    let mut response = validation_error(messages);
    response.1.0["path"] = json!(path);
    Some(response.into_response())
}
fn topic_not_found(topic: &str, env: &str, path: &str) -> Response {
    topic_error(
        StatusCode::NOT_FOUND,
        &format!("Topic not found for id {topic} in the environment {env}"),
        path,
    )
}
fn topic_not_empty(topic: &str, env: &str, path: &str) -> Response {
    topic_error(
        StatusCode::CONFLICT,
        &format!(
            "Topic with key {topic} in the environment {env} can't be deleted as it still has subscribers assigned"
        ),
        path,
    )
}
fn topic_dto(row: &tokio_postgres::Row, env: &str, topic: &str) -> Value {
    let mut result = json!({"_id":row.get::<_,String>(0),"_environmentId":env,"_organizationId":row.get::<_,String>(1),"key":topic,"createdAt":row.get::<_,String>(3),"updatedAt":row.get::<_,String>(4),"subscribers":row.get::<_,Vec<String>>(5)});
    if row.get::<_, bool>(7) {
        result["name"] = json!(row.get::<_, Option<String>>(2));
    }
    if let Some(data) = row.get::<_, Option<Value>>(6) {
        result["data"] = data;
    }
    result
}

pub async fn list(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    OriginalUri(uri): OriginalUri,
    Query(params): Query<HashMap<String, String>>,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(v) => v,
        Err(e) => return e.into_response(),
    };
    let number = |key: &str, default: i64| -> Option<i64> {
        match params.get(key) {
            None => Some(default),
            Some(value) if value.trim().is_empty() => Some(0),
            Some(value) => value.parse().ok(),
        }
    };
    let (Some(page), Some(size)) = (number("page", 0), number("pageSize", 10)) else {
        return topic_error(
            StatusCode::NOT_IMPLEMENTED,
            "Topic pagination not implemented",
            &path,
        );
    };
    let mut errors = Vec::new();
    if page < 0 {
        errors.push(("page", "page must not be less than 0", page));
    }
    if size < 0 {
        errors.push(("pageSize", "pageSize must not be less than 0", size));
    }
    if size > 10 {
        errors.push(("pageSize", "pageSize must not be greater than 10", size));
    }
    if !errors.is_empty() {
        let details = errors
            .iter()
            .map(|(field, message, _)| format!("{field}: {message}"))
            .collect::<Vec<_>>()
            .join("; ");
        let mut response = validation_error(Vec::new());
        response.1.0["path"] = json!(path);
        response.1.0["message"] = json!(format!(
            "Validation failed for FilterTopicsCommand: {details}"
        ));
        let fields: serde_json::Map<String, Value> = errors
            .into_iter()
            .map(|(field, message, value)| {
                (field.into(), json!({"messages":[message],"value":value}))
            })
            .collect();
        response.1.0["errors"] = Value::Object(fields);
        return response.into_response();
    }
    if size == 0 {
        let timestamp = chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Millis, true);
        return (StatusCode::INTERNAL_SERVER_ERROR, Json(json!({"statusCode":500,"timestamp":timestamp,"path":path,"message":"Internal server error, contact support and provide them with the errorId","errorId":uuid::Uuid::new_v4().to_string()}))).into_response();
    }
    let Some(offset) = page.checked_mul(size) else {
        return topic_error(
            StatusCode::NOT_IMPLEMENTED,
            "Topic pagination not implemented",
            &path,
        );
    };
    let key = params.get("key").filter(|value| !value.is_empty());
    let name = params.get("name").filter(|value| !value.is_empty());
    let row=db.query_one("WITH filtered AS MATERIALIZED (SELECT t.*,e.organization_id FROM novu_rust_topics t JOIN novu_rust_environments e ON e.id=t.environment_id WHERE t.environment_id=$1 AND ($2::text IS NULL OR t.topic_key=$2) AND ($3::text IS NULL OR t.name=$3)), page_rows AS (SELECT * FROM filtered ORDER BY internal_id LIMIT $4 OFFSET $5) SELECT (SELECT count(*) FROM filtered),COALESCE((SELECT jsonb_agg(jsonb_build_object('_id',p.internal_id,'_organizationId',p.organization_id,'_environmentId',p.environment_id,'key',p.topic_key,'createdAt',to_char(p.created_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),'updatedAt',to_char(p.updated_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),'subscribers',ARRAY(SELECT s.subscriber_id FROM novu_rust_topic_subscribers s WHERE s.environment_id=p.environment_id AND s.topic_key=p.topic_key ORDER BY s.created_at,s.subscriber_id)) || CASE WHEN p.name_present THEN jsonb_build_object('name',p.name) ELSE '{}'::jsonb END || CASE WHEN p.data IS NOT NULL THEN jsonb_build_object('data',p.data) ELSE '{}'::jsonb END ORDER BY p.internal_id) FROM page_rows p),'[]'::jsonb)",&[&env,&key,&name,&size,&offset]).await;
    match row {Ok(row)=>Json(json!({"page":page,"totalCount":row.get::<_,i64>(0),"pageSize":size,"data":row.get::<_,Value>(1)})).into_response(),Err(_)=>topic_error(StatusCode::INTERNAL_SERVER_ERROR,"Internal server error",&path)}
}

pub async fn create(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    OriginalUri(uri): OriginalUri,
    bytes: Bytes,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(v) => v,
        Err(e) => return e.into_response(),
    };
    let body: Value = match serde_json::from_slice(&bytes) {
        Ok(v) => v,
        Err(_) => return topic_error(StatusCode::BAD_REQUEST, "Invalid JSON", &path),
    };
    if let Some(error) = invalid_fields(&body, &["key", "name"], &path) {
        return error;
    }
    let key = body["key"].as_str().unwrap().trim();
    let name = body["name"].as_str().unwrap().trim();
    if key.is_empty() {
        return topic_error(
            StatusCode::NOT_IMPLEMENTED,
            "Topic key not implemented",
            &path,
        );
    }
    let org = match db
        .query_opt(
            "SELECT organization_id FROM novu_rust_environments WHERE id=$1",
            &[&env],
        )
        .await
    {
        Ok(Some(row)) => row.get::<_, String>(0),
        _ => {
            return topic_error(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Internal server error",
                &path,
            );
        }
    };
    let row=db.query_opt("INSERT INTO novu_rust_topics(environment_id,topic_key,internal_id,name) VALUES ($1,$2,novu_rust_new_objectid(),$3) ON CONFLICT (environment_id,topic_key) DO NOTHING RETURNING internal_id",&[&env,&key,&name]).await;
    match row {
        Ok(Some(row)) => (
            StatusCode::CREATED,
            Json(json!({"data":{"_id":row.get::<_,String>(0),"key":key}})),
        )
            .into_response(),
        Ok(None) => topic_error(
            StatusCode::CONFLICT,
            &format!(
                "Topic exists with key {key} in the environment {env} of the organization {org}"
            ),
            &path,
        ),
        Err(_) => topic_error(
            StatusCode::INTERNAL_SERVER_ERROR,
            "Internal server error",
            &path,
        ),
    }
}

pub async fn get(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    Path(topic): Path<String>,
    OriginalUri(uri): OriginalUri,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(v) => v,
        Err(e) => return e.into_response(),
    };
    let row=db.query_opt("SELECT t.internal_id,e.organization_id,t.name,to_char(t.created_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),to_char(t.updated_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),ARRAY(SELECT s.subscriber_id FROM novu_rust_topic_subscribers s WHERE s.environment_id=t.environment_id AND s.topic_key=t.topic_key ORDER BY s.created_at,s.subscriber_id),t.data,t.name_present FROM novu_rust_topics t JOIN novu_rust_environments e ON e.id=t.environment_id WHERE t.environment_id=$1 AND t.topic_key=$2",&[&env,&topic]).await;
    match row {
        Ok(Some(row)) => Json(json!({"data":topic_dto(&row,&env,&topic)})).into_response(),
        Ok(None) => topic_not_found(&topic, &env, &path),
        Err(_) => topic_error(
            StatusCode::INTERNAL_SERVER_ERROR,
            "Internal server error",
            &path,
        ),
    }
}

