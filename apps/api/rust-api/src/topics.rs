pub async fn rename(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    Path(topic): Path<String>,
    OriginalUri(uri): OriginalUri,
    bytes: Bytes,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(v) => v,
        Err(e) => return e.into_response(),
    };
    let body: Value = match serde_json::from_slice(&bytes) {
        Ok(v) => v,
        Err(_) => return topic_error(StatusCode::BAD_REQUEST, "Invalid JSON", &path),
    };
    if let Some(error) = invalid_fields(&body, &["name"], &path) {
        return error;
    }
    let name = body["name"].as_str().unwrap();
    let row=db.query_opt("WITH changed AS (UPDATE novu_rust_topics SET name=$3,name_present=true,updated_at=now() WHERE environment_id=$1 AND topic_key=$2 AND $3<>'' RETURNING *) SELECT t.internal_id,e.organization_id,t.name,to_char(t.created_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),to_char(t.updated_at AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"'),ARRAY(SELECT s.subscriber_id FROM novu_rust_topic_subscribers s WHERE s.environment_id=t.environment_id AND s.topic_key=t.topic_key ORDER BY s.created_at,s.subscriber_id),t.data,t.name_present FROM changed t JOIN novu_rust_environments e ON e.id=t.environment_id",&[&env,&topic,&name]).await;
    match row {
        Ok(Some(row)) => Json(json!({"data":topic_dto(&row,&env,&topic)})).into_response(),
        Ok(None) if name.is_empty() => match db
            .query_opt(
                "SELECT 1 FROM novu_rust_topics WHERE environment_id=$1 AND topic_key=$2",
                &[&env, &topic],
            )
            .await
        {
            Ok(Some(_)) => topic_error(StatusCode::BAD_REQUEST, "Name is required", &path),
            Ok(None) => topic_not_found(&topic, &env, &path),
            Err(_) => topic_error(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Internal server error",
                &path,
            ),
        },
        Ok(None) => topic_not_found(&topic, &env, &path),
        Err(_) => topic_error(
            StatusCode::INTERNAL_SERVER_ERROR,
            "Internal server error",
            &path,
        ),
    }
}

pub async fn delete(
    State(db): State<Arc<Client>>,
    headers: HeaderMap,
    Path(topic): Path<String>,
    OriginalUri(uri): OriginalUri,
) -> Response {
    let path = uri.to_string();
    let env = match authenticate(&db, &headers, &path).await {
        Ok(v) => v,
        Err(e) => return e.into_response(),
    };
    let result=db.query_one("WITH target AS MATERIALIZED (SELECT environment_id,topic_key FROM novu_rust_topics WHERE environment_id=$1 AND topic_key=$2 FOR UPDATE), removed AS (DELETE FROM novu_rust_topics t USING target WHERE t.environment_id=target.environment_id AND t.topic_key=target.topic_key AND NOT EXISTS(SELECT 1 FROM novu_rust_topic_subscribers s WHERE s.environment_id=t.environment_id AND s.topic_key=t.topic_key) RETURNING 1) SELECT EXISTS(SELECT 1 FROM target),EXISTS(SELECT 1 FROM removed)",&[&env,&topic]).await;
    match result {
        Ok(row) if row.get::<_, bool>(1) => StatusCode::NO_CONTENT.into_response(),
        Ok(row) if !row.get::<_, bool>(0) => topic_not_found(&topic, &env, &path),
        Ok(_) => topic_not_empty(&topic, &env, &path),
        Err(error)
            if error.as_db_error().is_some_and(|error| {
                error.code() == &tokio_postgres::error::SqlState::FOREIGN_KEY_VIOLATION
                    && error.constraint()
                        == Some("novu_rust_topic_subscribers_environment_id_topic_key_fkey")
            }) =>
        {
            topic_not_empty(&topic, &env, &path)
        }
        Err(_) => topic_error(
            StatusCode::INTERNAL_SERVER_ERROR,
            "Internal server error",
            &path,
        ),
    }
}
